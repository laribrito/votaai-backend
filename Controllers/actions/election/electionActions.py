class ElectionActions:
    """
    Orchestrates business logic for Desktop election creation:
    1. Structural validation of the ballot (questions and options).
    2. Validation of the requesting physical machine's digital signature.
    3. Normalized relational persistence: Election, Question, Option, and ElectoralCollege.
    4. Hardware TPM response signature generation (VotaAI_SecureKey_1).
    """

    @staticmethod
    def _extract_questions_and_options(ballot_data) -> tuple[list, int, int]:
        """
        Parses ballot data and returns:
        (questions_list, questions_count, options_count).
        """
        if isinstance(ballot_data, list):
            questions = ballot_data
        elif isinstance(ballot_data, dict):
            questions = ballot_data.get('questions', [])
        else:
            questions = []

        if not isinstance(questions, list) or len(questions) == 0:
            raise ValidationError({"ballot": _("The ballot must contain at least one question.")})

        questions_count = len(questions)
        options_count = 0

        for idx, q in enumerate(questions):
            if not isinstance(q, dict):
                raise ValidationError({"ballot": _("Question at index %(idx)s must be a JSON object.") % {'idx': idx}})

            options = q.get('options')
            if not isinstance(options, list) or len(options) == 0:
                q_name = q.get('question') or str(idx + 1)
                raise ValidationError({
                    "ballot": _("Question '%(q_name)s' must contain at least one option.") % {'q_name': q_name}
                })
            options_count += len(options)

        return questions, questions_count, options_count

    @classmethod
    def criarEleicao(cls, data: dict, raw_data: dict | None = None, user=None) -> dict:
        """
        Executes election creation and relational entities persistence:
        - Creates Election
        - Creates each Question and its child Options
        - Creates ElectoralCollege records
        - Signs response payload with server TPM (VotaAI_SecureKey_1)
        """
        title = str(data.get('title') or '').strip()
        ballot = data.get('ballot')
        electoral_college = data.get('electoral_college')
        public_key = str(data.get('public_key') or '').strip()
        key_handle = str(data.get('key_handle') or '').strip()
        machine_signature = str(data.get('signature') or '').strip()
        start_datetime = data.get('start_datetime')
        end_datetime = data.get('end_datetime')

        if not title:
            raise ValidationError({"title": _("The election title is required.")})
        if ballot is None:
            raise ValidationError({"ballot": _("The ballot structure is required.")})
        if electoral_college is None:
            raise ValidationError({"electoral_college": _("The electoral college is required.")})
        if not public_key:
            raise ValidationError({"public_key": _("The election public key is required.")})
        if not key_handle:
            raise ValidationError({"key_handle": _("The keyHandle is required.")})
        if not machine_signature:
            raise ValidationError({"signature": _("The machine digital signature is required.")})

        # 1. Validate ballot structure and compute counts
        questions_raw, questions_count, options_count = cls._extract_questions_and_options(ballot)

        # 2. Machine public key sent in the payload (single source of truth)
        machine_pub_key = str(data.get('machine_public_key') or '').strip().replace('\r\n', '\n')

        if not machine_pub_key:
            raise ValidationError({
                "machine_public_key": _("Machine public key is required.")
            })

        # 3. Validate digital signature generated by the client machine
        ballot_repr = json.dumps(ballot, sort_keys=True)
        college_repr = json.dumps(electoral_college, sort_keys=True)

        full_payload = raw_data if isinstance(raw_data, dict) else data
        is_valid_sig = SECryptoService.verify_payload_signature(machine_pub_key, full_payload)

        if not is_valid_sig:
            raise ValidationError({
                "signature": _("Physical machine signature is invalid or payload does not match.")
            })

        # Creator is the authenticated administrator bound to this machine public key
        norm_machine_pub_key = SECryptoService.to_pem_public_key(machine_pub_key)
        if not user or not getattr(user, 'is_authenticated', False):
            raise PermissionDenied(_("Authenticated administrator is required to create an election."))
        if not getattr(user, 'machine_public_key', None):
            raise PermissionDenied(_("Authenticated user is not bound to a physical machine."))
        norm_user_machine_key = SECryptoService.to_pem_public_key(user.machine_public_key)
        if norm_machine_pub_key.strip() != norm_user_machine_key.strip():
            raise PermissionDenied(_("The machine public key does not match the authenticated administrator's registered machine."))
        creator_user = user

        # Normalize public key to PEM format for cross-platform interoperability
        normalized_public_key = SECryptoService.to_pem_public_key(public_key)
        machine_fingerprint = SECryptoService.get_machine_fingerprint(norm_machine_pub_key)

        # 4. Atomic creation in normalized relational tables
        with transaction.atomic():
            if Election.objects.filter(key_handle=key_handle).exists():
                raise ValidationError({
                    "key_handle": _("An election with this keyHandle already exists.")
                })

            election = Election.objects.create(
                title=title,
                public_key=normalized_public_key,
                key_handle=key_handle,
                machine_fingerprint=machine_fingerprint,
                start_datetime=start_datetime,
                end_datetime=end_datetime,
                machine_signature=machine_signature,
                status=ElectionStatus.CREATED,
                created_by=creator_user
            )

            # Persist Question and child Option records
            for idx, q_data in enumerate(questions_raw):
                question_text = q_data.get('question') or f"Question {idx + 1}"
                order = q_data.get('order') or (idx + 1)

                question_obj = Question.objects.create(
                    election=election,
                    question=question_text,
                    order=order
                )

                options_raw = q_data.get('options') or []
                options_objs = []
                for opt in options_raw:
                    if isinstance(opt, dict):
                        label = opt.get('label') or str(opt)
                    else:
                        label = str(opt)
                    options_objs.append(Option(question=question_obj, label=label))
                
                if options_objs:
                    Option.objects.bulk_create(options_objs)

            # Persist ElectoralCollege records
            college_list = electoral_college if isinstance(electoral_college, list) else [electoral_college]
            voters_objs = []
            for voter in college_list:
                if isinstance(voter, dict):
                    email = (voter.get('email') or '').strip()
                    full_name = (
                        voter.get('full_name')
                        or voter.get('name')
                        or voter.get('nome')
                        or voter.get('nome_completo')
                        or voter.get('fullName')
                        or ''
                    ).strip()

                    if not full_name and email:
                        matched_user = User.objects.filter(email__iexact=email).first()
                        if matched_user:
                            user_full_name = f"{matched_user.first_name} {matched_user.last_name}".strip()
                            if user_full_name:
                                full_name = user_full_name

                    if not full_name and email:
                        full_name = email.split('@')[0]

                    # O apelido deve ser o primeiro nome do nome completo
                    nickname = ElectoralCollege.extract_first_name(full_name)

                    raw_pw = voter.get('password') or ''
                    if raw_pw:
                        if str(raw_pw).startswith(('pbkdf2_sha256$', 'argon2', 'bcrypt')):
                            password_hash = str(raw_pw)
                        else:
                            password_hash = make_password(str(raw_pw))
                    else:
                        password_hash = ''
                else:
                    email = str(voter).strip()
                    full_name = ''
                    if email:
                        matched_user = User.objects.filter(email__iexact=email).first()
                        if matched_user:
                            user_full_name = f"{matched_user.first_name} {matched_user.last_name}".strip()
                            if user_full_name:
                                full_name = user_full_name

                    if not full_name and email:
                        full_name = email.split('@')[0]

                    # O apelido deve ser o primeiro nome do nome completo
                    nickname = ElectoralCollege.extract_first_name(full_name)
                    password_hash = ''

                if email:
                    voters_objs.append(ElectoralCollege(
                        election=election,
                        full_name=full_name,
                        email=email,
                        nickname=nickname,
                        password=password_hash,
                        has_voted=False
                    ))

            if voters_objs:
                ElectoralCollege.objects.bulk_create(voters_objs, ignore_conflicts=True)

        # 5. Sign response payload with server TPM hardware key (VotaAI_SecureKey_1)
        data_to_sign = f"{election.id}:{questions_count}:{options_count}".encode('utf-8')
        try:
            server_signature = SECryptoService.sign_with_tpm('VotaAI_SecureKey_1', data_to_sign)
        except Exception as e:
            logger.error(f"Erro ao assinar resposta com TPM: {e}")
            raise RuntimeError(_("Error generating server digital signature: %(error)s") % {'error': str(e)})

        return {
            "id": election.id,
            "questions_count": questions_count,
            "options_count": options_count,
            "signature": server_signature
        }

    @classmethod
    def buscarEleicoesAbertas(cls, search_term: str | None = None):
        """
        Retorna as eleições públicas para acompanhamento a partir do status de iniciada
        (STARTED, CLOSED, TALLIED), excluindo rascunhos ainda não iniciados (CREATED).
        Contém contagem anotada de eleitores/votos para quórum e suporta busca por título.
        """
        qs = Election.objects.exclude(status=ElectionStatus.CREATED).annotate(
            total_voters=Count('electoral_college', distinct=True),
            voted_count=Count('electoral_college', filter=Q(electoral_college__has_voted=True), distinct=True)
        ).order_by('-start_datetime', '-created_at')

        if search_term:
            qs = qs.filter(title__icontains=search_term.strip())

        return qs

    @classmethod
    def obterAcompanhamentoEleicao(
        cls,
        election_id: int,
        voter_has_voted: bool | None = None,
        voter_search: str | None = None
    ) -> dict:
        """
        Retorna os dados públicos de acompanhamento de uma eleição específica para o quórum.
        Eleições com status CREATED não estão abertas e não podem ser visualizadas pelo público.
        Retorna apenas os dados necessários: metadados essenciais, resumo de quórum e o colegiado
        eleitoral com o status de votação (has_voted).
        """
        election = Election.objects.filter(id=election_id).first()
        if not election:
            raise Election.DoesNotExist(_("Election not found."))

        if election.status == ElectionStatus.CREATED:
            raise ValidationError({
                "election": _("This election is not open or available for public tracking.")
            })

        # Resumo geral de quórum
        total_voters = election.electoral_college.count()
        voted_count = election.electoral_college.filter(has_voted=True).count()
        pending_count = total_voters - voted_count
        quorum_percentage = round((voted_count / total_voters) * 100, 2) if total_voters > 0 else 0.0

        # Colegiado eleitoral
        voters_qs = election.electoral_college.all().order_by('full_name')

        if voter_has_voted is not None:
            voters_qs = voters_qs.filter(has_voted=voter_has_voted)

        if voter_search:
            search_str = voter_search.strip()
            voters_qs = voters_qs.filter(
                Q(full_name__icontains=search_str) |
                Q(nickname__icontains=search_str) |
                Q(email__icontains=search_str)
            )

        is_closed = election.status in (ElectionStatus.CLOSED, ElectionStatus.TALLIED)
        voters_data = [
            {
                "id": voter.id,
                "full_name": (
                    f"{voter.full_name} (Ausente)".strip()
                    if (not voter.has_voted and is_closed and not (voter.full_name or '').endswith("(Ausente)"))
                    else voter.full_name
                ),
                "nickname": voter.nickname,
                "email": voter.email,
                "has_voted": voter.has_voted
            }
            for voter in voters_qs
        ]

        is_tallied = election.status == ElectionStatus.TALLIED
        return {
            "id": election.id,
            "title": election.title,
            "status": election.status,
            "start_datetime": election.start_datetime,
            "end_datetime": election.end_datetime,
            "total_voters": total_voters,
            "voted_count": voted_count,
            "pending_count": pending_count,
            "quorum_percentage": quorum_percentage,
            "electoral_college": voters_data,
            "private_key": election.private_key if is_tallied else None,
            "tallies": [
                {
                    "id": t.id,
                    "tally_hash": t.tally_hash,
                    "tally_datetime": t.tally_datetime.isoformat() if hasattr(t.tally_datetime, 'isoformat') else str(t.tally_datetime)
                } for t in election.tallies.all().order_by('-tally_datetime')
            ] if is_tallied else [],
            "votes": [
                {
                    "id_generated": v.id_generated,
                    "content": v.content
                } for v in election.votes.all().order_by('id_generated')
            ] if is_tallied else []
        }

    @classmethod
    def _reembaralhar_urna_em_lote(cls, election: Election) -> None:
        """
        Re-embaralha criptograficamente as cédulas da urna em uma única transação
        no fechamento da eleição, uniformizando o xmin e aleatorizando a ordem física (ctid)
        com novos UUIDv4, além de limpar tickets não utilizados.
        """
        rng = secrets.SystemRandom()
        ballots = list(Vote.objects.filter(election=election).values('id_generated', 'content'))
        if ballots:
            rng.shuffle(ballots)
            Vote.objects.filter(election=election).delete()
            Vote.objects.bulk_create([
                Vote(
                    id=uuid.uuid4(),
                    election=election,
                    id_generated=b['id_generated'],
                    content=b['content'],
                )
                for b in ballots
            ])

        BallotTicket.objects.filter(election=election, is_used=False).delete()
        used_tickets = list(
            BallotTicket.objects.filter(election=election, is_used=True).values_list('id_voto', flat=True)
        )
        if used_tickets:
            rng.shuffle(used_tickets)
            BallotTicket.objects.filter(election=election, is_used=True).delete()
            BallotTicket.objects.bulk_create([
                BallotTicket(
                    id=uuid.uuid4(),
                    election=election,
                    id_voto=tv,
                    is_used=True,
                )
                for tv in used_tickets
            ])

    @classmethod
    def fecharEleicao(
        cls,
        data: dict,
        user: User | None = None,
        machine_public_key: str | None = None
    ) -> dict:
        """
        Encerra o período de votação de uma eleição ativa (STARTED).
        - Valida que a eleição existe e está no status STARTED.
        - Autentica a máquina/administrador criador da eleição.
        - Valida a assinatura digital específica da eleição gerada com a chave privada de hardware (key_handle).
        - Realiza a transição atômica de status para CLOSED e registra end_datetime.
        - Retorna métricas finais do quórum travado e o nonce de volta para a máquina cliente.
        """
        key_handle = data.get("keyHandle") or data.get("key_handle")
        election_signature = data.get("election_signature")
        nonce_client = (
            data.get("nonceClient3")
            or data.get("nonceClient")
            or data.get("nonceClient2")
            or data.get("nonce")
        )

        if not key_handle:
            raise ValidationError({"keyHandle": _("The election key handle is required.")})

        if not election_signature:
            raise ValidationError({"election_signature": _("Election signature is missing.")})

        # 1. Localiza a eleição pelo key_handle
        election = Election.objects.filter(key_handle=key_handle).order_by('-created_at').first()
        if not election:
            raise Election.DoesNotExist(_("Election not found."))

        # 2. Valida o status da eleição
        if election.status == ElectionStatus.CLOSED:
            raise ValidationError({"election": _("This election has already been closed.")})
        if election.status == ElectionStatus.TALLIED:
            raise ValidationError({"election": _("This election has already been tallied.")})
        if election.status == ElectionStatus.CREATED:
            raise ValidationError({"election": _("Cannot close an election that has not been started yet.")})
        if election.status != ElectionStatus.STARTED:
            raise ValidationError({"election": _("This election is not in an active voting state.")})

        # 3. Valida a permissão da máquina / administrador criador
        norm_machine_key = SECryptoService.to_pem_public_key(machine_public_key) if machine_public_key else None
        creator = election.created_by
        if not user or not getattr(user, 'is_authenticated', False):
            raise PermissionDenied(_("Authenticated administrator is required to close this election."))
        if creator and user.id != creator.id:
            raise PermissionDenied(_("Only the administrator that created this election can close it."))
        if creator and creator.machine_public_key:
            norm_creator_key = SECryptoService.to_pem_public_key(creator.machine_public_key)
            if not norm_machine_key or norm_machine_key.strip() != norm_creator_key.strip():
                raise PermissionDenied(_("Only the physical machine that created this election can close it."))

        # 4. Valida a assinatura digital específica da eleição (usando a public_key da eleição)
        payload_to_verify = dict(data)
        payload_to_verify.pop("election_signature", None)
        payload_to_verify.pop("signature", None)
        payload_to_verify.pop("machine_public_key", None)

        payload_bytes = json.dumps(
            payload_to_verify,
            sort_keys=True,
            separators=(',', ':'),
            ensure_ascii=False
        ).encode('utf-8')

        if not SECryptoService.verify_signature(election.public_key, payload_bytes, election_signature):
            raise PermissionDenied(_("Invalid election signature. Possible spoofing attempt."))

        # 5. Transição de estado atômica para CLOSED + re-embaralhamento em lote da urna
        with transaction.atomic():
            cls._reembaralhar_urna_em_lote(election)
            election.status = ElectionStatus.CLOSED
            election.end_datetime = timezone.now()
            election.save(update_fields=['status', 'end_datetime', 'updated_at'])

        # 6. Cálculo das métricas de quórum congelado
        total_voters = election.electoral_college.count()
        voted_count = election.electoral_college.filter(has_voted=True).count()
        pending_count = max(0, total_voters - voted_count)
        quorum_percentage = round((voted_count / total_voters) * 100, 2) if total_voters > 0 else 0.0

        machine_fp = election.machine_fingerprint or (
            SECryptoService.get_machine_fingerprint(election.created_by.machine_public_key)
            if election.created_by and getattr(election.created_by, 'machine_public_key', None)
            else ""
        )

        result = {
            "keyHandle": election.key_handle,
            "machine_fingerprint": machine_fp,
            "titulo": election.title,
            "status": election.status,
            "hora_registrada": election.end_datetime.isoformat(),
            "total_colegio": total_voters,
            "votos_registrados": voted_count,
            "pendentes": pending_count,
            "porcentagem_quorum": quorum_percentage,
            "mensagem": str(_("Election closed successfully. Voter quorum is locked."))
        }

        # Ecoa os nonces para proteção contra replay
        if data.get("nonceClient3"):
            result["nonceClient3"] = data.get("nonceClient3")
        if data.get("nonceClient"):
            result["nonceClient"] = data.get("nonceClient")
        if data.get("nonceClient2"):
            result["nonceClient2"] = data.get("nonceClient2")
        if nonce_client and not any(k in result for k in ("nonceClient3", "nonceClient", "nonceClient2")):
            result["nonceClient"] = nonce_client

        return result

    @classmethod
    def obterVotosEleicao(
        cls,
        data: dict,
        user: User | None = None,
        machine_public_key: str | None = None
    ) -> dict:
        """
        Retorna as cédulas cifradas de uma eleição encerrada (CLOSED) ou já apurada (TALLIED).
        Caso a eleição esteja em CLOSED (antes da apuração inicial), apenas a máquina física
        criadora autorizada pode resgatar os votos para realizar a primeira apuração soberana.
        """
        key_handle = data.get("keyHandle") or data.get("key_handle") or data.get("id")
        nonce_client = (
            data.get("nonceClient")
            or data.get("nonceClient3")
            or data.get("nonceClient2")
            or data.get("nonce")
        )

        if not key_handle:
            raise ValidationError({"keyHandle": _("The election key handle is required.")})

        # 1. Localiza a eleição
        if isinstance(key_handle, int) or (isinstance(key_handle, str) and key_handle.isdigit()):
            election = Election.objects.filter(id=int(key_handle)).first()
        else:
            election = Election.objects.filter(key_handle=key_handle).order_by('-created_at').first()

        if not election:
            raise Election.DoesNotExist(_("Election not found."))

        # 2. Valida o status da eleição
        if election.status not in (ElectionStatus.CLOSED, ElectionStatus.TALLIED):
            raise ValidationError({
                "election": _("Votes can only be retrieved for closed or tallied elections.")
            })

        # 3. Se a eleição está apenas CLOSED, restringe à máquina física/administrador criador
        if election.status == ElectionStatus.CLOSED:
            norm_machine_key = SECryptoService.to_pem_public_key(machine_public_key) if machine_public_key else None
            creator = election.created_by
            if not user or not getattr(user, 'is_authenticated', False):
                raise PermissionDenied(_("Authenticated administrator is required to retrieve votes for tallying."))
            if creator and user.id != creator.id:
                raise PermissionDenied(_("Only the administrator that created this election can retrieve votes for tallying."))
            if creator and creator.machine_public_key:
                norm_creator_key = SECryptoService.to_pem_public_key(creator.machine_public_key)
                if not norm_machine_key or norm_machine_key.strip() != norm_creator_key.strip():
                    raise PermissionDenied(_("Only the physical machine that created this election can retrieve votes for tallying."))

        # 4. Busca os votos da urna ordenados por identificador anônimo aleatório
        votes_qs = election.votes.all().order_by('id_generated')
        votes_data = [
            {
                "id_generated": vote.id_generated,
                "content": vote.content
            }
            for vote in votes_qs
        ]

        # 5. Estrutura descritiva das perguntas e opções para apuração legível
        questions_qs = election.questions.all().prefetch_related('options').order_by('order', 'id')
        questions_data = [
            {
                "id": q.id,
                "question": q.question,
                "order": q.order,
                "options": [
                    {"id": opt.id, "label": opt.label}
                    for opt in q.options.all().order_by('id')
                ]
            }
            for q in questions_qs
        ]

        total_voters = election.electoral_college.count()
        total_votos = len(votes_data)
        abstention_count = max(0, total_voters - total_votos)
        abstention_percentage = round((abstention_count / total_voters) * 100, 2) if total_voters > 0 else 0.0

        machine_fp = election.machine_fingerprint or (
            SECryptoService.get_machine_fingerprint(election.created_by.machine_public_key)
            if election.created_by and getattr(election.created_by, 'machine_public_key', None)
            else ""
        )

        result = {
            "keyHandle": election.key_handle,
            "machine_fingerprint": machine_fp,
            "titulo": election.title,
            "status": election.status,
            "total_votos": total_votos,
            "total_voters": total_voters,
            "abstention_count": abstention_count,
            "abstention_percentage": abstention_percentage,
            "votes": votes_data,
            "questions": questions_data
        }
        if nonce_client:
            result["nonceClient"] = nonce_client

        return result

    @classmethod
    def apurarEleicao(
        cls,
        data: dict,
        user: User | None = None,
        machine_public_key: str | None = None
    ) -> dict:
        """
        Salva a primeira apuração oficial e registra a chave privada da eleição no servidor.
        - Exige que a eleição esteja com status CLOSED.
        - Só pode ser gerada e enviada pela máquina desktop física autenticada que criou a eleição.
        - Valida matematicamente se a chave privada enviada deriva a chave pública da eleição.
        - Salva o registro de Tally (tally_hash) e persiste election.private_key.
        - Transiciona o status atômico para TALLIED, abrindo a eleição para apuração pública por qualquer pessoa.
        """
        key_handle = data.get("keyHandle") or data.get("key_handle") or data.get("id")
        tally_hash = data.get("tally_hash")
        private_key_pem = data.get("private_key")
        results = data.get("results")
        nonce_client = (
            data.get("nonceClient")
            or data.get("nonceClient3")
            or data.get("nonceClient2")
            or data.get("nonce")
        )

        if not key_handle:
            raise ValidationError({"keyHandle": _("The election key handle is required.")})
        if not tally_hash:
            raise ValidationError({"tally_hash": _("The tally cryptographic hash is required.")})
        if not private_key_pem:
            raise ValidationError({"private_key": _("The election private key is required for tally verification.")})
        if not results or not isinstance(results, dict):
            raise ValidationError({"results": _("The tally results are required and cannot be empty.")})

        # 1. Localiza a eleição
        if isinstance(key_handle, int) or (isinstance(key_handle, str) and key_handle.isdigit()):
            election = Election.objects.filter(id=int(key_handle)).first()
        else:
            election = Election.objects.filter(key_handle=key_handle).order_by('-created_at').first()

        if not election:
            raise Election.DoesNotExist(_("Election not found."))

        # 2. Valida o status da eleição
        if election.status == ElectionStatus.TALLIED:
            raise ValidationError({"election": _("This election has already been tallied.")})
        if election.status == ElectionStatus.STARTED:
            raise ValidationError({"election": _("Cannot tally an election while voting is still in progress. Close it first.")})
        if election.status == ElectionStatus.CREATED:
            raise ValidationError({"election": _("Cannot tally an election that has not been started.")})
        if election.status != ElectionStatus.CLOSED:
            raise ValidationError({"election": _("Election is not in a closed state.")})

        # 3. Validação estrita do Desktop Autenticado (Apenas máquina criadora autorizada)
        norm_machine_key = SECryptoService.to_pem_public_key(machine_public_key) if machine_public_key else None
        creator = election.created_by
        if not user or not getattr(user, 'is_authenticated', False):
            raise PermissionDenied(_("Authenticated administrator is required to tally this election."))
        if creator and user.id != creator.id:
            raise PermissionDenied(_("Only the administrator that created this election can tally it."))
        if creator and creator.machine_public_key:
            norm_creator_key = SECryptoService.to_pem_public_key(creator.machine_public_key)
            if not norm_machine_key or norm_machine_key.strip() != norm_creator_key.strip():
                raise PermissionDenied(_("Only the authenticated physical machine that created this election can tally it."))

        # 4. Validação criptográfica da Chave Privada da Eleição
        try:
            priv_bytes = private_key_pem.encode('utf-8') if isinstance(private_key_pem, str) else private_key_pem
            loaded_priv_key = serialization.load_pem_private_key(priv_bytes, password=None)
        except Exception:
            raise ValidationError({"private_key": _("Invalid private key format. PEM PKCS#8 expected.")})

        derived_pub_pem = loaded_priv_key.public_key().public_bytes(
            encoding=serialization.Encoding.PEM,
            format=serialization.PublicFormat.SubjectPublicKeyInfo
        ).decode('utf-8')

        normalized_election_pub = SECryptoService.to_pem_public_key(election.public_key)
        if not normalized_election_pub or derived_pub_pem.strip() != normalized_election_pub.strip():
            raise ValidationError({
                "private_key": _("The provided private key does not match the election's public key.")
            })

        election_questions = election.questions.all().prefetch_related('options').order_by('order', 'id')
        total_voters = election.electoral_college.count()
        total_votos = election.votes.count()
        abstention_count = max(0, total_voters - total_votos)
        abstention_percentage = round((abstention_count / total_voters) * 100, 2) if total_voters > 0 else 0.0

        # Normaliza a estrutura de questões em results
        structured_questions = results.get("questions")
        if not isinstance(structured_questions, list) or len(structured_questions) == 0:
            summary = results.get("summary") if isinstance(results.get("summary"), dict) else results
            built_questions = []
            for q in election_questions:
                q_dict = summary.get(q.question) or summary.get(str(q.id)) or summary.get(q.id) or {}
                opts_payload = []
                q_total = 0
                for opt in q.options.all().order_by('id'):
                    v_count = 0
                    if isinstance(q_dict, dict):
                        v_count = q_dict.get(opt.label) or q_dict.get(str(opt.id)) or q_dict.get(opt.id) or 0
                    opts_payload.append({
                        "id": opt.id,
                        "label": opt.label,
                        "votes": int(v_count)
                    })
                    q_total += int(v_count)

                for opt_item in opts_payload:
                    opt_item["percentage"] = round((opt_item["votes"] / q_total) * 100, 2) if q_total > 0 else 0.0

                built_questions.append({
                    "id": q.id,
                    "question": q.question,
                    "total_votes": q_total,
                    "options": opts_payload
                })
            structured_questions = built_questions

        # Validação de integridade estrita:
        # Se a eleição possui cédulas na urna, a apuração NÃO pode ter contagem zerada
        total_counted_votes = sum(
            sum(opt.get("votes", 0) for opt in q.get("options", []))
            for q in structured_questions
            if isinstance(q, dict)
        )
        if total_votos > 0 and election_questions.exists() and total_counted_votes == 0:
            raise ValidationError({
                "results": _("The tally results cannot be zeroed out when ballots exist in the election.")
            })

        normalized_results = {
            "summary": results.get("summary", {}),
            "questions": structured_questions,
            "total_votos": total_votos,
            "total_voters": total_voters,
            "abstention_count": abstention_count,
            "abstention_percentage": abstention_percentage
        }

        # 5. Persistência atômica do Tally e atualização de estado
        with transaction.atomic():
            tally = Tally.objects.create(
                election=election,
                tally_hash=str(tally_hash).strip(),
                tally_datetime=timezone.now(),
                results=normalized_results
            )
            election.private_key = private_key_pem.strip()
            election.status = ElectionStatus.TALLIED
            election.save(update_fields=['private_key', 'status', 'updated_at'])

        logger.info(
            f"[ELECTION_TALLIED] Eleição #{election.id} ('{election.title}') apurada com sucesso. "
            f"Tally #{tally.id} (hash: {tally.tally_hash[:16]}...). Chave privada liberada para auditoria pública."
        )

        machine_fp = election.machine_fingerprint or (
            SECryptoService.get_machine_fingerprint(election.created_by.machine_public_key)
            if election.created_by and getattr(election.created_by, 'machine_public_key', None)
            else ""
        )

        result = {
            "keyHandle": election.key_handle,
            "machine_fingerprint": machine_fp,
            "titulo": election.title,
            "status": election.status,
            "tally_id": tally.id,
            "tally_hash": tally.tally_hash,
            "tally_datetime": tally.tally_datetime.isoformat(),
            "total_voters": total_voters,
            "abstention_count": abstention_count,
            "abstention_percentage": abstention_percentage,
            "mensagem": str(_("Election tally saved successfully. Private key recorded for public verification."))
        }

        if results:
            result["results"] = results
        if nonce_client:
            result["nonceClient"] = nonce_client

        return result

    @classmethod
    def gerarPacoteAuditoria(cls, election_id: int) -> tuple[bytes, str]:
        """
        Gera o pacote ZIP oficial para auditoria de uma eleição apurada (TALLIED).
        Contém a chave privada da eleição em PEM e todos os votos criptografados.
        Retorna uma tupla (zip_bytes, filename).
        """
        try:
            election = Election.objects.prefetch_related('votes', 'tallies', 'questions__options').get(pk=election_id)
        except Election.DoesNotExist:
            raise Election.DoesNotExist(str(_("Election not found.")))

        if election.status != ElectionStatus.TALLIED:
            raise ValidationError({
                "election": str(_("Audit packages are only available for tallied elections (TALLIED)."))
            })

        if not election.private_key:
            raise ValidationError({
                "private_key": str(_("The private key for this election is not available."))
            })

        votes_qs = election.votes.all().order_by('id_generated')
        votes_data = [
            {
                "id_generated": v.id_generated,
                "content": v.content,
            }
            for v in votes_qs
        ]

        tally = election.tallies.order_by('-tally_datetime').first()
        machine_fp = election.machine_fingerprint or (
            SECryptoService.get_machine_fingerprint(election.created_by.machine_public_key)
            if election.created_by and getattr(election.created_by, 'machine_public_key', None)
            else ""
        )

        election_meta = {
            "id": election.id,
            "title": election.title,
            "key_handle": election.key_handle,
            "machine_fingerprint": machine_fp,
            "status": election.status,
            "start_datetime": election.start_datetime.isoformat() if election.start_datetime else None,
            "end_datetime": election.end_datetime.isoformat() if election.end_datetime else None,
            "public_key": election.public_key,
            "total_voters": election.electoral_college.count(),
            "total_votes": len(votes_data),
            "tally_hash": tally.tally_hash if tally else None,
            "tally_datetime": tally.tally_datetime.isoformat() if (tally and tally.tally_datetime) else None,
            "results": tally.results if tally else None,
            "questions": [
                {
                    "id": q.id,
                    "question": q.question,
                    "order": q.order,
                    "options": [
                        {"id": opt.id, "label": opt.label}
                        for opt in q.options.all().order_by('id')
                    ]
                }
                for q in election.questions.all().order_by('order', 'id')
            ]
        }

        readme_text = (
            f"==========================================================\n"
            f"VOTA AÍ - PACOTE OFICIAL DE AUDITORIA CRIPTOGRÁFICA\n"
            f"==========================================================\n\n"
            f"Eleição: {election.title} (ID #{election.id})\n"
            f"Handle da Eleição (key_handle): {election.key_handle}\n"
            f"Fingerprint da Máquina (machine_fingerprint): {machine_fp or 'N/A'}\n"
            f"Status: {election.status}\n"
            f"Hash de Apuração Oficial (SHA-256): {tally.tally_hash if tally else 'N/A'}\n"
            f"Total de Cédulas Cifradas: {len(votes_data)}\n\n"
            f"ARQUIVOS INCLUÍDOS:\n"
            f"1. chave_privada.pem: Chave privada da eleição utilizada para decifrar as cédulas.\n"
            f"2. votos_criptografados.json: Lista contendo todas as cédulas cifradas originais.\n"
            f"3. dados_eleicao.json: Metadados, questões e resultado canônico da eleição.\n\n"
            f"COMO AUDITAR NO APLICATIVO DESKTOP:\n"
            f"Importe este pacote no aplicativo desktop do Vota-i 2.0 na seção de Auditoria\n"
            f"para decifrar os votos, recalcular a apuração de forma soberana e conferir\n"
            f"a integridade matemática do pleito através do hash oficial.\n"
        )

        buffer = io.BytesIO()
        with zipfile.ZipFile(buffer, 'w', zipfile.ZIP_DEFLATED) as zip_file:
            priv_content = election.private_key.strip() + '\n'
            zip_file.writestr('chave_privada.pem', priv_content)

            votes_json = json.dumps(votes_data, indent=2, ensure_ascii=False)
            zip_file.writestr('votos_criptografados.json', votes_json)

            meta_json = json.dumps(election_meta, indent=2, ensure_ascii=False)
            zip_file.writestr('dados_eleicao.json', meta_json)

            zip_file.writestr('LEIAME.txt', readme_text)

        buffer.seek(0)
        filename = f"auditoria_eleicao_{election.id}.zip"
        return buffer.getvalue(), filename
